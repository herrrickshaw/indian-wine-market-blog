"""Characterisation harness: captures the observable behaviour of the repo's pure helpers.

tests/golden/characterisation.json was generated by running this against the
ORIGINAL (pre-refactor) code on main; test_characterisation.py asserts the
current code reproduces it byte-for-byte. Fully offline.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path


def capture(root: Path, scratch: Path) -> dict:
    """Run the helpers found under `root` on fixed inputs and return a JSON-able dict."""
    os.environ.setdefault("WINE_BLOG_ID", "1")
    os.environ.setdefault("WINE_BLOG_URL", "https://example.invalid")
    for sub in ("consistency-check", "tools"):
        p = str(root / sub)
        if p not in sys.path:
            sys.path.insert(0, p)
    import checks
    import fix
    import snapshot
    import svg_chart_lint

    fix.theme_css = lambda: ""  # never touch the network
    L = sys.modules.get("repair", fix)
    post = open(root / "out/post-eu-fta-wine-tariff-cut.html", encoding="utf-8").read()
    SYN = {
        "inverted": "<div class='post-body'><style>:root{--bg:#fff}@media not all and (prefers-color-scheme:dark){a{color:#eee} .x{b{c:d}}} p{color:red}</style><p>hi</p></div>",
        "spliced": '<div class="artx"><script>var h=\'<div>x<p class="disclaimer" data-gs-ai-disclosure-v1="1" style="a">AI</p>\n</div>\';</script></div>',
        "darkpanel": '<div class="artx"><style>:root{--panel:#101820;--ink:#111}.hero{background:var(--panel)}body{background:#0b1220}.card,.box{background:#182430}</style><p>x</p></div>',
        "empty": "",
    }
    out = {"rules": {}, "repair": {}, "snap": {}, "svg": {}}
    for name, src in {"post": post, **SYN}.items():
        out["rules"][name] = {
            r[0]: list(r[2](body=src, node_check=[])) for r in checks.STATIC_RULES
        }
        out["repair"][name] = list(fix.repair(src))
        out["repair"][name + "_static"] = fix.static_pass(src)
    out["body_of"] = fix.body_of("<x><div class='post-body'><div>a</div>b</div>tail")
    out["lum"] = [
        L._lum(c) for c in ["#fff", "#000", "#abc", "rgb(10,20,30)", "rgba(1,2,3,.5)", "zz", "#12"]
    ]
    out["panel"] = [L._is_panel(s) for s in ["body", ".hero", "main", "div p", "#x"]]
    A, B = "<p>Duty is 150 percent</p><h2>One</h2>", "<p>Duty is 120 percent</p><h2>One</h2>"
    out["snap"]["classify"] = [
        list(snapshot.classify(a, b) or ())
        for a, b in [
            (None, A),
            (A, A),
            (A, B),
            (A, A + "<style>x</style>"),
            (A, A + "<h2>Two</h2>"),
            (A, A.replace("Duty", "Tariff")),
            (A, A.replace("<h2>One</h2>", "")),
        ]
    ]
    out["snap"]["bump"] = [snapshot.bump("1.2.3", l) for l in ("major", "minor", "patch")]
    out["snap"]["slug"] = [
        snapshot.slug_of(u) for u in ["https://b.com/2026/01/foo-bar.html", "https://b.com/", ""]
    ]
    out["snap"]["with_ms"] = [
        snapshot._with_ms(t) for t in ["2026-01-01T16:00:00+05:30", "2026-01-01T16:00:00.123+05:30"]
    ]
    out["snap"]["markers"] = snapshot.markers(
        "gs-light-lock google_translate_element <script>AI Disclosure</script>"
    )
    out["snap"]["visible"] = snapshot.visible_text(
        "<style>a{}</style><p>A&amp;B  1,200</p><p data-gs-revision-v1>r 1.0</p>"
    )
    out["snap"]["headings"] = snapshot.headings("<h2> A <b>b</b></h2><h3>C</h3>")
    r = svg_chart_lint.lint_file(str(root / "out/post-eu-fta-wine-tariff-cut.html"))
    out["svg"]["post"] = r
    svg = '<svg viewBox="0 0 100 50"><text x="95" y="10" font-size="12">Very long label</text><text x="0" y="30">A</text><text x="2" y="30">B</text><rect x="0" y="20" width="50" height="20" fill="#000"/></svg>&amp;amp;'
    svg_path = scratch / "svg.html"
    svg_path.write_text(svg)
    out["svg"]["syn"] = svg_chart_lint.lint_file(str(svg_path))
    out["svg"]["tw"] = [svg_chart_lint.text_width("Hello 123", 12, b) for b in (False, True)]
    return out
